import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('./dashboard.js',import.meta.url),'utf8');
const elements=new Map();
const $=id=>{if(!elements.has(id))elements.set(id,{hidden:true,style:{},classList:{toggle(){},add(){}}});return elements.get(id);};
const state={reports:[],userReport:false,executionVersion:0};
const report=id=>({id,data:{results:[{rr:3,riskPercent:1}],config:{MinimumStop:3}}});
let reports=[report('custom-latest'),report('fxpro-20260101-20260501')];
const context=vm.createContext({$,state,api:async path=>path==='/api/reports'?reports:{jobs:[],dataDays:120},renderExecution(){},notify(){},fullRange:()=>({start:'a',end:'b'}),periodLabel:()=>'',fillSelect(){},chooseReport:id=>{state.report=reports.find(r=>r.id===id)||reports[0];}});
vm.runInContext('let refreshing=false;'+source.slice(source.indexOf('async function refresh()'),source.indexOf("for(const button of document.querySelectorAll('[data-page]'))button.onclick")),context);
await vm.runInContext('refresh()',context);
assert.equal(state.report.id,'custom-latest','First load opens newest saved report');
reports=[report('custom-newer'),...reports];
await vm.runInContext('refresh()',context);
assert.equal(state.report.id,'custom-newer','Automatic selection follows newly completed reports');
state.userReport=true;state.report=reports[2];
reports=[report('custom-newest'),...reports];
await vm.runInContext('refresh()',context);
assert.equal(state.report.id,'fxpro-20260101-20260501','Manual historical selection survives refresh');
console.log('Report selection PASS: newest on load/update, manual selection preserved.');
