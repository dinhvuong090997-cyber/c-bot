import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const window={};vm.runInNewContext(readFileSync(new URL('financial-chart.js',import.meta.url),'utf8'),{window});
const t=i=>`2026-01-05T00:00:${String(i).padStart(2,'0')}Z`;
const bars=[1,2,3,4,5].map(time=>({time,endUtc:t(time),open:100,high:102,low:99,close:101}));
const zone={index:3,long:true,low:99,high:101};
const events=[{zoneId:3,kind:'created',utc:t(3),zone},{zoneId:3,kind:'retest',utc:t(4),zone},{zoneId:3,kind:'invalidated',utc:t(5),zone}];
const data={bars,events},frame=window.rangePAFrame;
assert.equal(frame(data,1).zones.length,0,'zone invisible before confirmation');
assert.equal(frame(data,2).zones[0].state,'created');
assert.equal(frame(data,3).zones[0].state,'retest','future invalidation must not leak into replay');
assert.equal(frame(data,3).zones[0].endIndex,4,'active zone extends only to replay cursor');
assert.equal(frame(data,4).zones[0].state,'invalidated');
assert.equal(frame(data,4).zones[0].endIndex,5);
assert.equal(frame(data,1).markers.length,0);
assert(frame(data,3).markers.every(m=>m.time<=4));
const changed={bars,events:[...events,{zoneId:10,kind:'created',utc:t(9),zone:{...zone,index:10}}]};
assert.equal(JSON.stringify(frame(data,3)),JSON.stringify(frame(changed,3)),'appending future events preserves earlier frame');
console.log('Range PA replay PASS: confirmation timing, causal lifecycle, marker bounds and future-event invariance.');
