#!/usr/bin/env bash
# Gộp source thành 1 file kernel cho Kaggle (kernel chỉ nhận 1 code file).
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p kernel_features

{
  echo '# GENERATED by tools/build_features_kernel.sh - đừng sửa tay, sửa source rồi build lại'
  echo 'from __future__ import annotations'
  # bỏ future-import của từng file (phải nằm đầu file gộp, đã echo ở trên)
  grep -hv '^from __future__' data/bybit_api.py features/bar_features.py features/aux_features.py
  cat tools/kernel_features_runner.py
} > kernel_features/cbot_features.py

python3 -m py_compile kernel_features/cbot_features.py
echo "bundle OK: kernel_features/cbot_features.py"
