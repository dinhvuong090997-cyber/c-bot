#!/usr/bin/env bash
# Gộp source thành 1 file kernel cho Kaggle (kernel chỉ nhận 1 code file).
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p kernel_train

{
  echo '# GENERATED by tools/build_train_kernel.sh - đừng sửa tay, sửa source rồi build lại'
  echo 'from __future__ import annotations'
  echo 'import itertools, copy'
  echo 'from dataclasses import dataclass, field'
  echo 'import numpy as np, pandas as pd, torch, torch.nn as nn'
  echo 'from torch.utils.data import DataLoader, TensorDataset'
  echo 'from concurrent.futures import ThreadPoolExecutor, as_completed'
  # bỏ import nội bộ module (đã gộp chung 1 file) và future-import của từng file
  grep -hv '^from __future__\|^from model\.\|^import itertools\|^import copy\|^import numpy\|^import pandas\|^import torch\|^from torch\|^from concurrent\|^from dataclasses' \
    model/labels.py model/dataset.py model/net.py model/train.py model/sweep.py
  cat tools/kernel_train_runner.py
} > kernel_train/cbot_train.py

python3 -m py_compile kernel_train/cbot_train.py
echo "bundle OK: kernel_train/cbot_train.py"
