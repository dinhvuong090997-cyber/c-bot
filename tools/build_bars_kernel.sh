#!/usr/bin/env bash
# Gộp bars/pipeline.py + kernel_bars_runner.py thành 1 file kernel Kaggle,
# baked theo khoảng ngày cụ thể (Bybit script kernel không nhận env var).
#
# Dùng: tools/build_bars_kernel.sh <out_dir> <start_date> <end_date> <kaggle_slug>
# vd:   tools/build_bars_kernel.sh kernel_bars_2020_2022 2020-03-25 2022-07-05 cbot-bars-2020-2022
set -euo pipefail
cd "$(dirname "$0")/.."

OUT_DIR="$1"; START_DATE="$2"; END_DATE="$3"; SLUG="$4"
mkdir -p "$OUT_DIR"

{
  echo "# GENERATED by tools/build_bars_kernel.sh - đừng sửa tay, sửa source rồi build lại"
  grep -v '^if __name__ == "__main__":' bars/pipeline.py | sed '/^    cfg = Config()$/,$d'
  sed "s/__START_DATE__/${START_DATE}/; s/__END_DATE__/${END_DATE}/" tools/kernel_bars_runner.py
} > "$OUT_DIR/cbot_bars.py"

python3 -m py_compile "$OUT_DIR/cbot_bars.py"

cat > "$OUT_DIR/kernel-metadata.json" <<EOF
{
  "id": "vuongnguyen0909/${SLUG}",
  "title": "${SLUG}",
  "code_file": "cbot_bars.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": false,
  "enable_internet": true
}
EOF

echo "bundle OK: $OUT_DIR/cbot_bars.py (${START_DATE} -> ${END_DATE}, slug=${SLUG})"
